export const BANK_ENTRIES: DirEntry[] = [];
BANK_DIR.forEach(([group, names]) =>
  names.forEach(n =>
    BANK_ENTRIES.push({
      name: n,
      group,
      type: 'bank' as const,
      hay: norm(n) + ' ' + (BANK_ALIAS[n] || '') + ' ' + norm(group),
    }),
  ),
);
export const CARD_ENTRIES: DirEntry[] = [];
CARD_DIR.forEach(([issuer, alias, prods]) => {
  prods.forEach(p =>
    CARD_ENTRIES.push({
      name: issuer + ' ' + p,
      group: issuer,
      type: 'card' as const,
      hay: norm(issuer + ' ' + p) + ' ' + alias + ' credit card',
    }),
  );
  CARD_ENTRIES.push({
    name: issuer + ' credit card (other)',
    group: issuer,
    type: 'card' as const,
    hay: norm(issuer) + ' ' + alias + ' other credit card any',
  });
});
export const DIR: Record<'bank' | 'card', DirEntry[]> = { bank: BANK_ENTRIES, card: CARD_ENTRIES };
